/**
 * Validates content/ + data/generated/ and writes
 *   build/content.json   resolved content (input for content:push and the scheduler)
 *   supabase/seed.sql    the same as idempotent SQL for the local Supabase
 *
 *   npm run content:build
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parse as parseYaml } from "yaml";
import type { z } from "zod";
import {
  AliasFile,
  Entity,
  EntityFile,
  FamiliarityFile,
  QuestionFile,
  type Question,
} from "../src/lib/content/schema";
import { resolveContent, type ResolvedQuestion } from "../src/lib/content/resolve";
import { normalize } from "../src/lib/game/normalize";

const ROOT = path.resolve(import.meta.dirname, "..");
const rel = (...p: string[]) => path.join(ROOT, ...p);

async function listFiles(dir: string, ext: string): Promise<string[]> {
  const names = await readdir(dir).catch(() => [] as string[]);
  return names.filter((n) => n.endsWith(ext)).sort().map((n) => path.join(dir, n));
}

async function loadEntities(): Promise<Entity[]> {
  const entities: Entity[] = [];
  for (const file of await listFiles(rel("data", "generated"), ".json")) {
    entities.push(...parseWith(EntityFile, file, JSON.parse(await readFile(file, "utf8"))));
  }
  for (const file of await listFiles(rel("content", "entities"), ".yaml")) {
    entities.push(...parseWith(EntityFile, file, parseYaml(await readFile(file, "utf8"))));
  }

  const overrides: Record<string, number> = {};
  for (const file of await listFiles(rel("content", "familiarity"), ".yaml")) {
    Object.assign(overrides, parseWith(FamiliarityFile, file, parseYaml(await readFile(file, "utf8"))));
  }
  const known = new Set(entities.map((e) => e.id));
  for (const id of Object.keys(overrides)) {
    if (!known.has(id)) throw new Error(`content/familiarity: unbekannte Entity ${id}`);
  }
  const extraAliases: Record<string, string[]> = {};
  for (const file of await listFiles(rel("content", "aliases"), ".yaml")) {
    for (const [id, aliases] of Object.entries(parseWith(AliasFile, file, parseYaml(await readFile(file, "utf8"))))) {
      if (!known.has(id)) throw new Error(`${path.relative(ROOT, file)}: unbekannte Entity ${id}`);
      extraAliases[id] = [...(extraAliases[id] ?? []), ...aliases];
    }
  }

  return entities.map((e) => ({
    ...e,
    familiarity: overrides[e.id] ?? e.familiarity,
    aliases: extraAliases[e.id] ? [...e.aliases, ...extraAliases[e.id]] : e.aliases,
  }));
}

async function loadQuestions(): Promise<Question[]> {
  const questions: Question[] = [];
  for (const file of await listFiles(rel("content", "questions"), ".yaml")) {
    questions.push(...parseWith(QuestionFile, file, parseYaml(await readFile(file, "utf8"))));
  }
  return questions;
}

function parseWith<T>(schema: z.ZodType<T>, file: string, data: unknown): T {
  const result = schema.safeParse(data);
  if (!result.success) {
    const issues = result.error.issues.map((i) => `  ${i.path.join(".")}: ${i.message}`).join("\n");
    throw new Error(`${path.relative(ROOT, file)}\n${issues}`);
  }
  return result.data;
}

// --- SQL --------------------------------------------------------------------

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const textArray = (a: string[]) => `array[${a.map(lit).join(",")}]::text[]`;

function insertChunks(head: string, rows: string[], conflict: string, size = 500): string {
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += size) {
    out.push(`${head}\nvalues\n  ${rows.slice(i, i + size).join(",\n  ")}\n${conflict};`);
  }
  return out.join("\n\n");
}

function aliasesOf(e: Entity): string[] {
  return [...new Set([e.names.de, e.names.en, ...e.aliases].map(normalize).filter(Boolean))];
}

function buildSeedSql(entities: Entity[], questions: ResolvedQuestion[]): string {
  const entityRows = entities.map(
    (e) => `(${lit(e.id)}, ${lit(e.kind)}, ${json(e.names)}, ${json(e.attrs)}, ${e.familiarity})`,
  );
  const aliasRows = entities.flatMap((e) => aliasesOf(e).map((a) => `(${lit(a)}, ${lit(e.id)})`));
  const questionRows = questions.map(
    (q) =>
      `(${lit(q.id)}, ${lit(q.category)}, ${q.group ? lit(q.group) : "null"}, ${q.difficulty}, ${q.timeLimitS}, ` +
      `${q.cooldownDays}, ${json(q.prompt)}, ${textArray(q.universe)}, ${lit(q.masterball)}, ${q.active}, ` +
      `${q.source ? lit(q.source) : "null"})`,
  );
  const answerRows = questions.flatMap((q) =>
    Object.entries(q.answerPriors).map(([id, share]) => `(${lit(q.id)}, ${lit(id)}, ${share})`),
  );

  return [
    "-- GENERATED by `npm run content:build` – do not edit. Source: content/ + data/generated/",
    "begin;",
    insertChunks(
      "insert into entities (id, kind, names, attrs, familiarity)",
      entityRows,
      "on conflict (id) do update set kind = excluded.kind, names = excluded.names, attrs = excluded.attrs, familiarity = excluded.familiarity, updated_at = now()",
    ),
    "delete from entity_aliases;",
    insertChunks("insert into entity_aliases (alias, entity_id)", aliasRows, "on conflict do nothing"),
    insertChunks(
      "insert into questions (id, category, question_group, difficulty, time_limit_s, cooldown_days, prompt, universe, masterball_entity_id, active, source)",
      questionRows,
      "on conflict (id) do update set category = excluded.category, question_group = excluded.question_group, difficulty = excluded.difficulty, time_limit_s = excluded.time_limit_s, cooldown_days = excluded.cooldown_days, prompt = excluded.prompt, universe = excluded.universe, masterball_entity_id = excluded.masterball_entity_id, active = excluded.active, source = excluded.source, updated_at = now()",
    ),
    `delete from question_answers where question_id in (${questions.map((q) => lit(q.id)).join(", ")});`,
    insertChunks("insert into question_answers (question_id, entity_id, prior_share)", answerRows, ""),
    "commit;",
    "",
  ].join("\n\n");
}

// --- main -------------------------------------------------------------------

async function main() {
  const entities = await loadEntities();
  const { questions, problems } = resolveContent(entities, await loadQuestions());

  for (const p of problems) {
    console.log(`${p.level === "error" ? "✗" : "⚠"} ${p.where}: ${p.message}`);
  }
  const errors = problems.filter((p) => p.level === "error").length;
  if (errors > 0) {
    console.error(`\n${errors} Fehler – Build abgebrochen.`);
    process.exit(1);
  }

  // Only ship entities that can actually be guessed.
  const kinds = new Set(questions.flatMap((q) => q.universe));
  const shipped = entities.filter((e) => kinds.has(e.kind));

  await mkdir(rel("build"), { recursive: true });
  await writeFile(rel("build", "content.json"), JSON.stringify({ entities: shipped, questions }, null, 2));
  await writeFile(rel("supabase", "seed.sql"), buildSeedSql(shipped, questions));

  console.log(`\n✓ ${questions.length} Fragen, ${shipped.length} Entitäten (${[...kinds].join(", ")})`);
  for (const q of questions) {
    const n = Object.keys(q.answerPriors).length;
    console.log(`  ${q.id.padEnd(28)} ${String(n).padStart(4)} Antworten · Universum: ${q.universe.join(", ")}${q.active ? "" : " · inaktiv"}`);
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
